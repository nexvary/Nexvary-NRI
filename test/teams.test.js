import assert from 'node:assert/strict';
import { once } from 'node:events';
import { test } from 'node:test';
import { createApp } from '../src/server.js';
import { openWorkspaceStore } from '../src/store.js';

test('project roles gate direct actions, bind consent to an invitation, and preserve attributable history', async (t) => {
  const store = openWorkspaceStore();
  const [owner, manager, researcher, reviewer, reader, stranger] = ['owner', 'manager', 'researcher', 'reviewer', 'reader', 'stranger'].map((name) => {
    const email = name + '@team.test';
    store.addAccount(email, { salt: Buffer.alloc(16), hash: Buffer.alloc(32) });
    const { id } = store.credentials(email);
    store.network.save(id, { name, interests: '', orcid: '', discoverable: true });
    return { id, cookie: 'nri_session=' + store.newSession(id) };
  });
  const project = store.createProject(owner.id, { title: 'Field study', description: '' });
  const other = store.createProject(stranger.id, { title: 'Unrelated private study', description: '' });
  store.evidence.addClaim(owner.id, project, 'A documented claim');
  const [claim] = store.evidence.list(owner.id, project);
  store.references.save(owner.id, project, { doi: '10.0000/test', provider: 'crossref', checkedAt: 42, status: 'found', metadata: { title: 'Field study source' } });
  store.evidence.link(owner.id, project, { claim: claim.id, doi: '10.0000/test', provider: 'crossref', relation: 'supports', studyType: '', limitations: '' });
  const item = store.evidence.list(owner.id, project)[0].evidence[0].id;
  const app = createApp(store);
  app.listen(0, '127.0.0.1');
  await once(app, 'listening');
  t.after(() => new Promise((resolve) => app.close(resolve)));
  const origin = 'http://127.0.0.1:' + app.address().port;
  const path = '/workspace/projects/' + project + '/team?lang=en';
  const inbox = '/workspace/team-invitations?lang=en';
  const request = (user, url, fields, source = origin) => fetch(origin + url, {
    redirect: 'manual', headers: { cookie: user.cookie, ...(fields ? { origin: source } : {}) },
    ...(fields ? { method: 'POST', body: new URLSearchParams(fields) } : {}),
  });
  const grant = (actor, user, role) => request(actor, path, { intent: 'invite', peer: user.id, role });
  const invitation = (user) => store.teams.inbox(user.id)[0].invitation;
  const accept = (user, role, invite = invitation(user)) => request(user, inbox, { intent: 'accepted', project, role, invitation: invite });
  assert.equal((await grant(owner, manager, 'administrator')).status, 303);
  assert.equal((await request(manager, path)).status, 404);
  assert.match(await (await request(manager, '/?lang=en')).text(), /Team invitations · 1/);
  assert.equal((await accept(manager, 'administrator')).status, 303);
  assert.doesNotMatch(await (await request(manager, '/?lang=en')).text(), /Team invitations · 1/);
  assert.equal((await grant(manager, reader, 'administrator')).status, 422);
  assert.equal((await grant(manager, researcher, 'researcher')).status, 303);
  assert.equal((await grant(manager, reviewer, 'reviewer')).status, 303);
  assert.equal((await grant(manager, reader, 'read-only')).status, 303);
  const old = invitation(reader);
  assert.equal((await grant(owner, reader, 'researcher')).status, 303);
  assert.equal((await accept(reader, 'read-only', old)).status, 404);
  assert.equal((await grant(owner, reader, 'read-only')).status, 303);
  assert.equal((await accept(reader, 'read-only', old)).status, 404);
  assert.equal((await accept(reader, 'read-only')).status, 303);
  assert.equal((await accept(researcher, 'researcher')).status, 303);
  assert.equal((await accept(reviewer, 'reviewer')).status, 303);
  assert.equal((await request(stranger, path)).status, 404);
  assert.equal((await request(researcher, '/workspace/projects/' + project + '?lang=en')).status, 404);
  assert.equal((await request(reader, path, { intent: 'save', title: 'Denied', body: 'Denied' })).status, 403);
  assert.equal((await request(reviewer, path, { intent: 'save', title: 'Denied', body: 'Denied' })).status, 403);
  assert.equal((await request(owner, path, { intent: 'save', title: 'Denied', body: 'Denied' }, 'https://foreign.test')).status, 403);
  const created = await request(researcher, path, { intent: 'save', title: 'Draft', body: 'Version one' });
  assert.equal(created.status, 303);
  const manuscriptPath = created.headers.get('location');
  const manuscript = new URL(origin + manuscriptPath).searchParams.get('manuscript');
  assert.equal((await request(researcher, path, { intent: 'save', manuscript, base: 1, body: 'Version two' })).status, 303);
  assert.equal((await request(researcher, path, { intent: 'save', manuscript, base: 1, body: 'Stale version' })).status, 409);
  assert.equal((await request(stranger, '/workspace/projects/' + other + '/team?lang=en&manuscript=' + manuscript)).status, 404);
  const [, first] = store.teams.view(reviewer.id, project, manuscript).versions;
  assert.equal(first.author, researcher.id);
  assert.equal((await request(researcher, path, { intent: 'review', version: first.id, outcome: 'accepted', note: 'Denied' })).status, 403);
  assert.equal((await request(reviewer, path, { intent: 'review', version: first.id, outcome: 'changes-requested', note: 'Clarify the methodology' })).status, 303);
  assert.equal((await request(reviewer, path, { intent: 'review', item, outcome: 'accepted', note: 'Source matches the claim' })).status, 303);
  const html = await (await request(reader, manuscriptPath)).text();
  assert.match(html, /Version one/);
  assert.match(html, /Version two/);
  assert.match(html, /Clarify the methodology/);
  assert.match(html, /Source matches the claim/);
  assert.doesNotMatch(html, /Team activity|Unrelated private study|Save new version/);
  assert.ok(store.teams.view(owner.id, project).events.some((event) => event.actor === reviewer.id && event.action === 'review'));
  const work = '/workspace/projects/' + project + '/team/work?lang=en';
  assert.equal((await request(stranger, work)).status, 404);
  assert.equal((await request(reader, work, { intent: 'note', text: 'Denied' })).status, 403);
  assert.equal((await request(researcher, work, { intent: 'note', text: '<script>Shared note</script>' })).status, 303);
  assert.equal((await request(researcher, work, { intent: 'task', text: 'Verify sources' })).status, 303);
  const [task] = store.teams.work(owner.id, project, 0).tasks;
  assert.equal((await request(reviewer, work, { intent: 'task-state', task: task.id, from: 'open', to: 'done' })).status, 403);
  assert.equal((await request(manager, work, { intent: 'task-state', task: task.id, from: 'open', to: 'done' })).status, 303);
  assert.equal((await request(researcher, work, { intent: 'task-state', task: task.id, from: 'open', to: 'done' })).status, 409);
  const sharedWork = await (await request(reader, work)).text();
  assert.match(sharedWork, /&lt;script&gt;Shared note&lt;\/script&gt;/);
  assert.match(sharedWork, /Verify sources/);
  assert.doesNotMatch(sharedWork, /Mark as done|Reopen task/);
  assert.ok(store.teams.view(owner.id, project).events.some((event) => event.actor === manager.id && event.action === 'task-done'));
  assert.equal((await request(manager, path, { intent: 'revoke', peer: reviewer.id })).status, 303);
  assert.equal((await request(reviewer, manuscriptPath)).status, 404);
  assert.ok(store.network.interact(owner.id, reader.id, 'block'));
  assert.equal((await request(reader, manuscriptPath)).status, 404);
  assert.ok(store.network.interact(owner.id, reader.id, 'unblock'));
  assert.equal((await request(reader, manuscriptPath)).status, 404);
});
